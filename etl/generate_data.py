"""
Synthetic e-commerce sales data generator.

Produces a single flat dataset (one row per order) matching the project's
column spec, with realistic structure baked in rather than pure randomness:

- Revenue grows ~35% from the start to the end of the window, with a
  Nov/Dec holiday seasonal bump and a smaller August back-to-school bump.
- The South and West regions carry the largest share of order volume.
- Electronics carries the thinnest margins of any category, so heavily
  discounted electronics orders occasionally post a loss - a real pattern
  worth surfacing later in the "business insights" feature.
- A minority of customers order repeatedly (order counts are drawn from a
  skewed log-normal distribution, not sampled uniformly), so repeat-customer
  and CLV analysis in later phases has something real to find.

No third-party dependency beyond pandas/numpy: customer and product names
are generated by combining small hand-written word pools rather than
pulling in Faker, since it isn't needed at runtime and this keeps data
generation dependency-free.
"""

